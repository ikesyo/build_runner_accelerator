#!/usr/bin/env bash
set -euo pipefail

# Verify synchronous build compilation (the strict force policy), the
# default policy's deferred publication, output recovery, and the CI-style
# AOT prewarm contract across two relocated workspaces:
# prewarm one workspace, copy only the generated worker/AOT cache, and build
# the second workspace without recompiling the AOT executable.

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
repo_root=$(cd -- "$script_dir/.." && pwd)

source "$script_dir/toolchain.sh"
source "$script_dir/worker.sh"
fixture_dir="$repo_root/fixtures/current_json_app"
dart_bin=$(resolve_toolchain_dart)
pub_cache=$(resolve_toolchain_pub_cache)
temporary_dir=$(mktemp -d)
# Keep the machine-wide accelerator cache hermetic: these scenarios assert
# on whether a workspace compiles or reuses its AOT worker.
export BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/shared-cache"
workspace_parent="$temporary_dir/workspaces"
workspace_a="$workspace_parent/a"
workspace_b="$workspace_parent/b"
workspace_cold="$workspace_parent/cold"
cold_log="$temporary_dir/cold.log"
recovery_log="$temporary_dir/recovery.log"
prewarm_log="$temporary_dir/prewarm.log"
build_log="$temporary_dir/build.log"

remove_tree() {
  local path=$1
  [[ -e "$path" || -L "$path" ]] || return 0
  if [[ -L "$path" ]]; then
    rm -f -- "$path"
    return 0
  fi
  find "$path" -depth -type f -delete
  find "$path" -depth -type l -delete
  find "$path" -depth -type d -empty -delete
}

cleanup() {
  if [[ -n "${watchcfg_pid:-}" ]]; then
    worker_stop_process_group "$watchcfg_pid" || true
  fi
  remove_tree "$temporary_dir"
}
trap cleanup EXIT INT TERM

# Compile/reuse evidence comes from the published artifact, not the build
# log: the frontend captures compiler output (its stdout names a temporary
# artifact), so a compile is observable only as the executable being
# (re)published, which updates its mtime.
aot_mtime_ns() {
  python3 -c 'import os, sys; print(os.stat(sys.argv[1]).st_mtime_ns)' "$1"
}

fail() {
  printf 'aot-prewarm: FAIL: %s\n' "$*" >&2
  for log in "$cold_log" "$recovery_log" "$prewarm_log" "$build_log" "$temporary_dir/deferred.log" "$temporary_dir/watchcfg.log" "$temporary_dir/watchcfg-twin.log" "$temporary_dir/watchcfg-reuse.log"; do
    if [[ -f "$log" ]]; then
      printf '%s\n' "--- $log ---" >&2
      sed -n '1,260p' "$log" >&2
    fi
  done
  exit 1
}

[[ -x "$dart_bin" ]] || fail "Dart executable not found: $dart_bin"
worker_ensure_frontend || fail 'Rust frontend build failed'
fast_bin="$BUILD_RUNNER_ACCELERATOR_BIN"

mkdir -p "$workspace_parent"
worker_attach "$temporary_dir"

setup_workspace() {
  local root=$1
  mkdir -p "$root/lib"
  cp "$fixture_dir/pubspec.yaml" "$root/pubspec.yaml"
  cp "$fixture_dir/pubspec.lock" "$root/pubspec.lock"
  cp "$fixture_dir/build.yaml" "$root/build.yaml"
  cp "$fixture_dir/lib"/*.dart "$root/lib/"
  (cd "$root" && PUB_CACHE="$pub_cache" "$dart_bin" \
    --suppress-analytics pub get --offline >/dev/null) || fail "pub get failed: $root"
}

run_runner() {
  local root=$1
  local log=$2
  shift 2
  VERIFY_COMMAND_LOG="$log" \
    BUILD_RUNNER_ACCELERATOR_WORKER_AOT="${AOT_POLICY:-1}" BUILD_RUNNER_ACCELERATOR_BIN="$fast_bin" \
    worker_run_frontend \
    "$@" --root "$root" --dart "$dart_bin"
}

# Keep this cache separate from the prewarm/relocation scenario: under the
# strict force policy a build must compile synchronously even when neither
# workspace nor machine cache is warm.
setup_workspace "$workspace_cold"
cold_marker="$temporary_dir/cold-start.marker"
touch "$cold_marker"
AOT_POLICY=force BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/cold-cache" \
  run_runner "$workspace_cold" "$cold_log" build || fail 'cold synchronous AOT build failed'
cold_aot_root="$workspace_cold/.dart_tool/build_runner_accelerator/aot-sdk"
cold_aot="$cold_aot_root/bin/dynamic_worker"
if [[ ! -f "$cold_aot" && -f "$cold_aot.exe" ]]; then
  cold_aot="$cold_aot.exe"
fi
[[ -x "$cold_aot" ]] || fail 'cold build did not publish an executable'
[[ -L "$cold_aot_root/lib" ]] || fail 'cold build did not publish SDK lib facade'
[[ -L "$cold_aot_root/version" ]] || fail 'cold build did not publish SDK version facade'
[[ "$cold_aot" -nt "$cold_marker" ]] || fail 'cold build did not compile AOT worker'
[[ -f "$workspace_cold/lib/model_01.g.dart" ]] || fail 'cold build produced no output'
mv "$workspace_cold/lib/model_01.g.dart" "$temporary_dir/expected-model-01.g.dart"
cold_mtime_before=$(aot_mtime_ns "$cold_aot")
AOT_POLICY=force BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/cold-cache" \
  run_runner "$workspace_cold" "$recovery_log" build || fail 'output recovery build failed'
cmp "$temporary_dir/expected-model-01.g.dart" "$workspace_cold/lib/model_01.g.dart" || \
  fail 'deleted output was not regenerated byte-identically'
[[ "$(aot_mtime_ns "$cold_aot")" == "$cold_mtime_before" ]] || \
  fail 'output recovery recompiled unchanged AOT worker'

setup_workspace "$workspace_a"
setup_workspace "$workspace_b"

run_runner "$workspace_a" "$prewarm_log" prewarm || fail 'AOT prewarm failed'

generated_dir="$workspace_a/.dart_tool/build_runner_accelerator"
aot_root="$generated_dir/aot-sdk"
aot_path="$aot_root/bin/dynamic_worker"
if [[ ! -f "$aot_path" && -f "$aot_path.exe" ]]; then
  aot_path="$aot_path.exe"
fi
[[ -x "$aot_path" ]] || fail 'prewarm did not publish an executable'
[[ -f "$aot_path.d" ]] || fail 'prewarm did not publish a depfile'
[[ -f "$aot_path.sdk" ]] || fail 'prewarm did not publish SDK metadata'

mkdir -p "$workspace_b/.dart_tool/build_runner_accelerator"
cp -a "$workspace_a/.dart_tool/build_runner_accelerator/aot-sdk" \
  "$workspace_b/.dart_tool/build_runner_accelerator/"
cp "$workspace_a/.dart_tool/build_runner_accelerator/dynamic_worker.dart" \
  "$workspace_b/.dart_tool/build_runner_accelerator/"
cp "$workspace_a/.dart_tool/build_runner_accelerator/builder-manifest.json" \
  "$workspace_b/.dart_tool/build_runner_accelerator/"

# A cache restore can leave SDK facade symlinks pointing at the prewarm
# runner's absolute SDK path. The next invocation must repair them against the
# current runner's SDK before deciding whether the executable is reusable.
rm -f -- "$workspace_b/.dart_tool/build_runner_accelerator/aot-sdk/lib" \
  "$workspace_b/.dart_tool/build_runner_accelerator/aot-sdk/version"
ln -s "$temporary_dir/missing-sdk/lib" \
  "$workspace_b/.dart_tool/build_runner_accelerator/aot-sdk/lib"
ln -s "$temporary_dir/missing-sdk/version" \
  "$workspace_b/.dart_tool/build_runner_accelerator/aot-sdk/version"

b_aot="$workspace_b/.dart_tool/build_runner_accelerator/aot-sdk/bin/dynamic_worker"
if [[ ! -f "$b_aot" && -f "$b_aot.exe" ]]; then
  b_aot="$b_aot.exe"
fi
b_mtime_before=$(aot_mtime_ns "$b_aot")
run_runner "$workspace_b" "$build_log" build || fail 'cached AOT build failed'
[[ -f "$workspace_b/lib/model_01.g.dart" ]] || fail 'cached AOT build produced no output'
[[ "$(aot_mtime_ns "$b_aot")" == "$b_mtime_before" ]] || \
  fail 'cached AOT build compiled the worker again'

# Compare internal metadata after the relocated build has reused the artifact.
# Cache identity is an implementation detail, not a public CLI command.
python3 - "$aot_path.sdk" "$workspace_b/.dart_tool/build_runner_accelerator/aot-sdk/bin/$(basename "$aot_path").sdk" <<'PYKEY'
import json
import sys
from pathlib import Path
first = json.loads(Path(sys.argv[1]).read_text())["cache_key"]
second = json.loads(Path(sys.argv[2]).read_text())["cache_key"]
assert first == second, "relocated workspaces produced different cache keys"
PYKEY

printf '\n// AOT prewarm relocation probe\n' \
  >>"$workspace_b/.dart_tool/build_runner_accelerator/dynamic_worker.dart"
# Publish a matching manifest/source pair so the frontend accepts the changed
# catalog. An unpaired edit is repaired by manifest generation before AOT cache
# validation and therefore cannot exercise source invalidation here.
python3 - "$workspace_b/.dart_tool/build_runner_accelerator" <<'PY'
import json
import sys
from pathlib import Path

generated = Path(sys.argv[1])
digest = 0xcbf29ce484222325
for byte in (generated / 'dynamic_worker.dart').read_bytes():
    digest = ((digest ^ byte) * 0x100000001b3) & 0xffffffffffffffff
manifest_path = generated / 'builder-manifest.json'
manifest = json.loads(manifest_path.read_text())
manifest['worker_source_digest'] = f'{digest:016x}'
manifest_path.write_text(json.dumps(manifest) + '\n')
PY
cp "$workspace_b/.dart_tool/build_runner_accelerator/dynamic_worker.dart" \
  "$temporary_dir/expected-worker.dart"
rm -f -- "$workspace_b/lib/model_02.g.dart"
b_mtime_before=$(aot_mtime_ns "$b_aot")
# The synchronous invalidation assertion runs under the force policy: the
# default policy now starts on the kernel and republishes AOT after exit.
AOT_POLICY=force run_runner "$workspace_b" "$build_log" build || fail 'invalidation build failed'
[[ -f "$workspace_b/lib/model_02.g.dart" ]] || fail 'invalidation build produced no output'
cmp "$temporary_dir/expected-worker.dart" \
  "$workspace_b/.dart_tool/build_runner_accelerator/dynamic_worker.dart" || \
  fail 'invalidation input was replaced before AOT validation'
[[ -x "$b_aot" ]] || fail 'invalidation build did not publish an executable'
b_mtime_after=$(aot_mtime_ns "$b_aot") || \
  fail 'could not read invalidation AOT executable mtime'
[[ "$b_mtime_after" != "$b_mtime_before" ]] || \
  fail 'changed worker did not invalidate AOT cache'

# Default policy with a warm manifest snapshot but cold AOT caches: the
# build starts on a kernel worker and the AOT artifact is published by the
# deferred helper after the build exits. (A first build generates the
# manifest; its early compile is expected and warms the snapshot.)
# Platforms without a process-liveness probe spawn no deferred helper, so
# the publication assertions only run where the helper exists.
deferred_result=na
case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) ;;
  *)
    workspace_deferred="$workspace_parent/deferred"
    deferred_log="$temporary_dir/deferred.log"
    setup_workspace "$workspace_deferred"
    AOT_POLICY=force BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/deferred-cache" \
      run_runner "$workspace_deferred" "$temporary_dir/deferred-warm.log" build || \
      fail 'deferred warm-up build failed'
    deferred_state="$workspace_deferred/.dart_tool/build_runner_accelerator"
    rm -rf -- "$deferred_state/aot-sdk" "$deferred_state/graph-v3.bin"
    find "$workspace_deferred/lib" -name '*.g.dart' -delete
    AOT_POLICY=1 BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/deferred-cache-cold" \
      run_runner "$workspace_deferred" "$deferred_log" build || fail 'deferred cold build failed'
    [[ -f "$workspace_deferred/lib/model_01.g.dart" ]] || fail 'deferred cold build produced no output'
    grep -Fq 'using kernel while AOT compiles in background' "$deferred_log" || \
      fail 'deferred cold build did not start on the kernel worker'
    deferred_aot="$workspace_deferred/.dart_tool/build_runner_accelerator/aot-sdk/bin/dynamic_worker"
    if [[ ! -f "$deferred_aot" && -f "$deferred_aot.exe" ]]; then
      deferred_aot="$deferred_aot.exe"
    fi
    for _ in $(seq 1 90); do
      [[ -x "$deferred_aot" ]] && break
      sleep 2
    done
    [[ -x "$deferred_aot" ]] || fail 'deferred helper did not publish an executable after the build exited'
    deferred_result=yes
    ;;
esac

# A watch session under a non-default --config spawns the background
# AOT helper on a cold cache. The helper must compile the worker the
# session generated under that config, not regenerate the entrypoint
# or manifest from its own default options, and the published
# artifact must be reusable by a later build under the same config.
# The twin workspace pins the expected catalog with a synchronous
# force-policy build under the same config (no helper involved).
watchcfg_result=na
case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) ;;
  *)
    workspace_twin="$workspace_parent/watchcfg-twin"
    workspace_watch="$workspace_parent/watchcfg"
    watchcfg_log="$temporary_dir/watchcfg.log"
    watchcfg_reuse_log="$temporary_dir/watchcfg-reuse.log"
    setup_workspace "$workspace_twin"
    setup_workspace "$workspace_watch"
    for root in "$workspace_twin" "$workspace_watch"; do
      printf 'targets:\n  $default:\n    builders:\n      json_serializable:\n        enabled: false\n' \
        >"$root/build.custom.yaml"
    done
    AOT_POLICY=force BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/watchcfg-twin-cache" \
      run_runner "$workspace_twin" "$temporary_dir/watchcfg-twin.log" build --config custom || \
      fail 'watch-config twin build failed'
    twin_worker="$workspace_twin/.dart_tool/build_runner_accelerator/dynamic_worker.dart"
    [[ -f "$twin_worker" ]] || fail 'watch-config twin build generated no worker'
    if cmp -s "$twin_worker" \
      "$workspace_a/.dart_tool/build_runner_accelerator/dynamic_worker.dart"; then
      fail 'custom config did not change the generated worker'
    fi
    # Pin the background policy explicitly: the launcher forwards an
    # inherited WORKER_AOT value, and the one-shot value 1 selects
    # the synchronous policy instead, whose deferred helper waits
    # for the session to exit and never publishes during the watch.
    worker_start_frontend_process_group "$watchcfg_log" \
      PUB_CACHE="$pub_cache" BUILD_RUNNER_ACCELERATOR_BIN="$fast_bin" \
      BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/watchcfg-cache" \
      BUILD_RUNNER_ACCELERATOR_WORKER_AOT=background -- \
      watch --config custom --root "$workspace_watch" --dart "$dart_bin" || \
      fail 'watch-config watch failed to start'
    watchcfg_pid=$worker_last_pid
    watchcfg_aot="$workspace_watch/.dart_tool/build_runner_accelerator/aot-sdk/bin/dynamic_worker"
    if [[ ! -f "$watchcfg_aot" && -f "$watchcfg_aot.exe" ]]; then
      watchcfg_aot="$watchcfg_aot.exe"
    fi
    for _ in $(seq 1 90); do
      [[ -x "$watchcfg_aot" ]] && break
      kill -0 "$watchcfg_pid" 2>/dev/null || fail 'watch-config watch exited before publishing'
      sleep 2
    done
    [[ -x "$watchcfg_aot" ]] || fail 'watch background helper did not publish an executable'
    kill -0 "$watchcfg_pid" 2>/dev/null || fail 'watch-config watch exited after publishing'
    cmp "$twin_worker" \
      "$workspace_watch/.dart_tool/build_runner_accelerator/dynamic_worker.dart" || \
      fail 'watch background helper rewrote the worker entrypoint'
    # The manifest embeds the workspace's absolute path; compare the
    # two manifests with each root normalized out.
    python3 - \
      "$workspace_twin/.dart_tool/build_runner_accelerator/builder-manifest.json" \
      "$workspace_watch/.dart_tool/build_runner_accelerator/builder-manifest.json" \
      "$workspace_twin" "$workspace_watch" <<'PY' || \
      fail 'watch background helper rewrote the builder manifest'
import json
import sys

def load(path, root):
    return json.loads(open(path).read().replace(root, '<root>'))

assert load(sys.argv[1], sys.argv[3]) == load(sys.argv[2], sys.argv[4]), \
    'manifests differ beyond the workspace root'
PY
    worker_stop_process_group "$watchcfg_pid"
    watchcfg_pid=
    watchcfg_mtime_before=$(aot_mtime_ns "$watchcfg_aot")
    # Validate the published artifact synchronously: a build under
    # this config has no actions (the builder is disabled), so it
    # would never start a worker. A force-policy prewarm under the
    # same config resolves the worker from the local slot instead,
    # and a fresh shared cache leaves that slot as the only reuse
    # source; a wrong-catalog artifact would be recompiled here.
    AOT_POLICY=force BUILD_RUNNER_ACCELERATOR_CACHE="$temporary_dir/watchcfg-reuse-cache" \
      run_runner "$workspace_watch" "$watchcfg_reuse_log" prewarm --config custom || \
      fail 'watch-config reuse prewarm failed'
    [[ "$(aot_mtime_ns "$watchcfg_aot")" == "$watchcfg_mtime_before" ]] || \
      fail 'watch-config reuse prewarm recompiled the worker'
    watchcfg_result=yes
    ;;
esac

printf 'aot-prewarm: build-sync-compile=yes output-delete-recovery=yes compile-wait=yes cache-key-portable=yes cache-reuse=yes invalidation=yes deferred-publish=%s watch-config-helper=%s\n' "$deferred_result" "$watchcfg_result"
