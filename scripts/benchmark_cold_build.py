#!/usr/bin/env python3
"""Alternate prepared native frontends in the same fixture and cache paths.

Run pub resolution and a normal AOT build first. This harness excludes launcher,
AOT compilation and AOT validation (explicit worker path), retains SDK summaries,
and empties byte_store/dep_parse for cold. It does not flush the OS page cache.
Supports tracked JSON/2-input Riverpod and the prepared shared-source fixture.
Use only a disposable fixture/cache: generated files, graphs and cache entries
are removed. Inputs are restored even after failure. Real source edits must
change generated bytes in the one-file and broad cases.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import statistics
import subprocess
import time

from benchmark_shared_byte_store import clear_graph, wait_for_process


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('baseline', 'candidate', 'frontend-dart', 'root', 'cache', 'results'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--fixture-kind', choices=('json', 'riverpod', 'riverpod-shared', 'riverpod-cycle'), default='json')
    parser.add_argument('--stock-check', action='store_true',
                        help='Prepare untimed stock output references for every edit case')
    parser.add_argument('--worker', type=Path, help='Prepared baseline worker')
    parser.add_argument('--candidate-worker', type=Path,
                        help='Prepared candidate worker in the same fixture SDK layout')
    parser.add_argument('--jobs', type=int, nargs='+', default=[1, 2, 4])
    parser.add_argument('--repeats', type=int, default=5)
    parser.add_argument('--retain-dep-parse', action='store_true',
                        help='Retain directive caches while clearing the analyzer byte store')
    parser.add_argument('--metrics', action='store_true', help='Diagnostic runs; separate from timings')
    parser.add_argument('--trace', action='store_true', help='Per-asset/phase diagnostics; requires --metrics')
    parser.add_argument('--aot-cold', action='store_true',
                        help='Include manifest/kernel/probe/worker compilation; measure cold only')
    parser.add_argument('--baseline-package', type=Path)
    parser.add_argument('--candidate-package', type=Path)
    args = parser.parse_args()
    if args.trace and not args.metrics:
        parser.error('--trace requires --metrics; traces must not enter timing runs')
    if args.repeats < 1 or any(j < 1 for j in args.jobs):
        parser.error('repeats and jobs must be positive')
    if args.aot_cold:
        if not args.baseline_package or not args.candidate_package:
            parser.error('--aot-cold requires both package roots')
    elif not args.worker:
        parser.error('prepared comparisons require --worker')
    for name in ('baseline', 'candidate', 'frontend_dart', 'root', 'cache', 'results'):
        setattr(args, name, getattr(args, name).resolve())
    if args.worker:
        args.worker = args.worker.resolve()
    if args.cache == args.root or args.cache in args.root.parents:
        parser.error('cache must not contain the fixture')
    args.results.mkdir(parents=True, exist_ok=True)
    candidate_worker = args.candidate_worker.resolve() if args.candidate_worker else args.worker
    config_path = args.root / '.dart_tool/package_config.json'
    original_config = config_path.read_bytes()
    source_pattern = ('model_*.dart' if args.fixture_kind == 'json' else
                      'provider_*.dart' if args.fixture_kind in ('riverpod-shared', 'riverpod-cycle') else '*.dart')
    sources = {p: p.read_bytes() for p in (args.root / 'lib').glob(source_pattern)
               if not p.name.endswith(('.g.dart', '.freezed.dart'))}
    if not sources:
        parser.error('requires prepared model fixture')
    environment = dict(os.environ, BUILD_RUNNER_ACCELERATOR_CACHE=str(args.cache),
                       BUILD_RUNNER_ACCELERATOR_METRICS=str(int(args.metrics)),
                       BUILD_RUNNER_ACCELERATOR_ANALYSIS_TRACE=str(int(args.trace)))
    environment.pop('BUILD_RUNNER_ACCELERATOR_WORKER_AOT_PATH', None)
    environment['BUILD_RUNNER_ACCELERATOR_WORKER_AOT'] = '1'
    environment.pop('BUILD_RUNNER_ACCELERATOR_ANALYSIS_SINGLE_FLIGHT', None)
    records, expected = [], {}

    def restore():
        for p, content in sources.items():
            p.write_bytes(content)

    def outputs(root=args.root, stock=False):
        paths = list((root / 'lib').glob('*.g.dart'))
        paths += list((root / 'lib').glob('*.freezed.dart'))
        cache = root / ('.dart_tool/build/generated' if stock else
                        '.dart_tool/build_runner_accelerator/cache')
        parts = list(cache.rglob('*.g.part'))
        return {**{str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
                   for p in paths},
                **{'cache/' + str(p.relative_to(cache)): hashlib.sha256(p.read_bytes()).hexdigest()
                   for p in parts}}

    def edit(content, broad):
        if args.fixture_kind == 'json':
            return re.sub(rb'\bvalue\b', b'valueBroad' if broad else b'valueEdited', content)
        # Rename provider functions: edits must change generated bytes, unlike
        # editing only the function body. The tracked Riverpod fixture has two.
        return re.sub(rb'\b(answer[0-9]*|greeting)\b',
                      lambda m: m[0] + (b'Broad' if broad else b'Edited'), content)

    metadata = dict(sdk=subprocess.check_output([str(args.frontend_dart), '--version'], text=True).strip(),
                    root=str(args.root), cache=str(args.cache), worker=str(args.worker),
                    fixture_kind=args.fixture_kind, trace=args.trace, stock_check=args.stock_check,
                    jobs=args.jobs, repeats=args.repeats, metrics=args.metrics,
                    dep_parse='retained' if args.retain_dep_parse else 'cleared',
                    sdk_summary='retained', os_page_cache='not flushed',
                    aot_cold=args.aot_cold,
                    worker_sha256={lane: hashlib.sha256(worker.read_bytes()).hexdigest()
                                   for lane, worker in [('baseline', args.worker), ('candidate', candidate_worker)]}
                                   if not args.aot_cold else None,
                    binary_sha256={lane: hashlib.sha256(getattr(args, lane).read_bytes()).hexdigest()
                                   for lane in ('baseline', 'candidate')},
                    package_config_sha256=hashlib.sha256(original_config).hexdigest(),
                    pubspec_lock_sha256=hashlib.sha256((args.root / 'pubspec.lock').read_bytes()).hexdigest(),
                    source_sha256={str(p.relative_to(args.root)): hashlib.sha256(p.read_bytes()).hexdigest()
                                   for p in (args.root / 'lib').glob('*.dart')
                                   if not p.name.endswith(('.g.dart', '.freezed.dart'))},
                    sdk_summary_override=environment.get('ANALYZER_STATE_LOCATION_OVERRIDE'))
    (args.results / 'metadata.json').write_text(json.dumps(metadata, indent=2) + '\n')
    stock_expected = {}
    if args.stock_check:
        stock_root = args.results / 'stock'
        stock_root.mkdir()
        for name in ('pubspec.yaml', 'pubspec.lock', 'build.yaml'):
            if (args.root / name).exists():
                shutil.copy2(args.root / name, stock_root / name)
        shutil.copytree(args.root / 'lib', stock_root / 'lib')
        (stock_root / '.dart_tool').mkdir()
        config = json.loads(original_config)
        package_name = next(p['name'] for p in config['packages']
                            if p['rootUri'] in ('../', args.root.as_uri() + '/'))
        for package in config['packages']:
            if package['name'] == package_name:
                package['rootUri'] = stock_root.as_uri() + '/'
        (stock_root / '.dart_tool/package_config.json').write_text(json.dumps(config))
        for case in ('cold', 'warm-clean', 'no-op', 'one-file', 'broad'):
            for p, content in sources.items():
                target = stock_root / 'lib' / p.name
                target.write_bytes(edit(content, broad=True) if case == 'broad' else
                                   edit(content, broad=False) if case == 'one-file' and p == sorted(sources)[0]
                                   else content)
            with (args.results / f'stock-{case}.log').open('w') as log:
                subprocess.run([str(args.frontend_dart), '--suppress-analytics', 'run',
                                'build_runner', 'build', '--delete-conflicting-outputs'],
                               cwd=stock_root, env=environment, stdout=log, stderr=log,
                               check=True, timeout=300)
            stock_expected[case] = outputs(stock_root, stock=True)
        (args.results / 'stock-outputs.json').write_text(json.dumps(stock_expected, indent=2))
    try:
        for jobs in args.jobs:
            for repeat in range(args.repeats):
                for lane in (('baseline', 'candidate') if repeat % 2 == 0 else ('candidate', 'baseline')):
                    restore()
                    if args.aot_cold:
                        config = json.loads(original_config)
                        package_root = getattr(args, lane + '_package').resolve()
                        for package in config['packages']:
                            if package['name'] == 'build_runner_accelerator':
                                package['rootUri'] = package_root.as_uri() + '/'
                        config_path.write_text(json.dumps(config))
                        shutil.rmtree(args.root / '.dart_tool/build_runner_accelerator', ignore_errors=True)
                        for name in ('worker-aot', 'manifest-kernel', 'probe'):
                            shutil.rmtree(args.cache / name, ignore_errors=True)
                    cache_names = ('byte_store',) if args.retain_dep_parse else ('byte_store', 'dep_parse')
                    for name in cache_names:
                        shutil.rmtree(args.cache / name, ignore_errors=True)
                    cases = ('cold',) if args.aot_cold else ('cold', 'warm-clean', 'no-op', 'one-file', 'broad')
                    for case in cases:
                        if case in ('cold', 'warm-clean'):
                            clear_graph(args.root)
                            for p in (args.root / 'lib').glob('*.freezed.dart'):
                                p.unlink()
                        if case == 'one-file':
                            p = sorted(sources)[0]
                            p.write_bytes(edit(sources[p], broad=False))
                        if case == 'broad':
                            for p, content in sources.items():
                                p.write_bytes(edit(content, broad=True))
                        command = [str(getattr(args, lane)), 'build', '--root', str(args.root),
                                   '--dart', str(args.frontend_dart), '--mode', 'rust', '--jobs', str(jobs)]
                        log = args.results / f'{jobs}-{repeat}-{lane}-{case}.log'
                        start = time.perf_counter()
                        with log.open('w') as stream:
                            worker = args.worker if lane == 'baseline' else candidate_worker
                            run_env = dict(environment)
                            if not args.aot_cold:
                                run_env['BUILD_RUNNER_ACCELERATOR_WORKER_AOT_PATH'] = str(worker)
                            process = subprocess.Popen(command, cwd=args.root, env=run_env,
                                                       stdout=stream, stderr=stream, start_new_session=True)
                            usage = wait_for_process(process, 300)
                        wall = time.perf_counter() - start
                        if process.returncode:
                            raise subprocess.CalledProcessError(process.returncode, command)
                        hashes = outputs()
                        if args.fixture_kind == 'json':
                            assert len(hashes) == len(sources) * 2, log
                        elif args.fixture_kind == 'riverpod':
                            assert len(hashes) == 6, log
                        else:
                            assert len(hashes) == len(sources) * (4 if args.fixture_kind == 'riverpod-cycle' else 2), log
                        if args.stock_check:
                            assert hashes == stock_expected[case], f'{log}: differs from stock'
                        if case in ('one-file', 'broad'):
                            assert hashes != expected['cold'], log
                        if case in expected:
                            assert hashes == expected[case], log
                        expected[case] = hashes
                        if case == 'no-op':
                            assert 'No work to do (Rust frontend)' in log.read_text(), log
                        row = dict(jobs=jobs, repeat=repeat, lane=lane, case=case, wall_s=wall,
                                   cpu_s=usage.ru_utime + usage.ru_stime, max_process_rss_kib=usage.ru_maxrss,
                                   output_sha256=hashes, command=command, log=str(log))
                        records.append(row)
                        (args.results / 'builds.json').write_text(json.dumps(records, indent=2) + '\n')
                        print(jobs, repeat, lane, case, round(wall, 4), flush=True)
    finally:
        restore()
        config_path.write_bytes(original_config)
    summary = []
    for jobs in args.jobs:
        for case in ('cold', 'warm-clean', 'no-op', 'one-file', 'broad'):
            for lane in ('baseline', 'candidate'):
                rows = [r for r in records if (r['jobs'], r['case'], r['lane']) == (jobs, case, lane)]
                values = [r['wall_s'] for r in rows]
                if not values:
                    continue
                summary.append(dict(jobs=jobs, case=case, lane=lane, samples=values,
                                    median_s=statistics.median(values), min_s=min(values), max_s=max(values),
                                    cpu_s=statistics.median(r['cpu_s'] for r in rows)))
    (args.results / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')


if __name__ == '__main__':
    main()
